"""Writes src/regexp/names.rs, the names \\p{...} may use in a pattern.

    python3 scripts/gen-regexp-names.py

The General_Category and Script values, with their aliases, are
PropertyValueAliases.txt from the Unicode Character Database (Unicode
License v3) at the version below, the one src/unicode.rs and test262
use. The binary properties and the properties of strings are ECMA-262's
tables of them. Only the names are kept: validating a pattern needs no
code points. Each list is sorted, for a binary search.
"""

import subprocess
import urllib.request

VERSION = "17.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/PropertyValueAliases.txt"

# ECMA-262's table of binary Unicode properties, names and aliases.
BINARY = """
ASCII ASCII_Hex_Digit AHex Alphabetic Alpha Any Assigned Bidi_Control
Bidi_C Bidi_Mirrored Bidi_M Case_Ignorable CI Cased
Changes_When_Casefolded CWCF Changes_When_Casemapped CWCM
Changes_When_Lowercased CWL Changes_When_NFKC_Casefolded CWKCF
Changes_When_Titlecased CWT Changes_When_Uppercased CWU Dash
Default_Ignorable_Code_Point DI Deprecated Dep Diacritic Dia Emoji
Emoji_Component EComp Emoji_Modifier EMod Emoji_Modifier_Base EBase
Emoji_Presentation EPres Extended_Pictographic ExtPict Extender Ext
Grapheme_Base Gr_Base Grapheme_Extend Gr_Ext Hex_Digit Hex
IDS_Binary_Operator IDSB IDS_Trinary_Operator IDST ID_Continue IDC
ID_Start IDS Ideographic Ideo Join_Control Join_C
Logical_Order_Exception LOE Lowercase Lower Math
Noncharacter_Code_Point NChar Pattern_Syntax Pat_Syn
Pattern_White_Space Pat_WS Quotation_Mark QMark Radical
Regional_Indicator RI Sentence_Terminal STerm Soft_Dotted SD
Terminal_Punctuation Term Unified_Ideograph UIdeo Uppercase Upper
Variation_Selector VS White_Space space XID_Continue XIDC XID_Start
XIDS
""".split()

# ECMA-262's table of binary Unicode properties of strings, for the v
# flag.
STRINGS = """
Basic_Emoji Emoji_Keycap_Sequence RGI_Emoji_Modifier_Sequence
RGI_Emoji_Flag_Sequence RGI_Emoji_Tag_Sequence RGI_Emoji_ZWJ_Sequence
RGI_Emoji
""".split()

values = {"gc": set(), "sc": set()}
for line in urllib.request.urlopen(URL).read().decode("utf-8").splitlines():
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    fields = [f.strip() for f in line.split(";")]
    if fields[0] in values:
        values[fields[0]].update(f for f in fields[1:] if f and f != "n/a")


def table(name, doc, names):
    items = ", ".join(f'"{n}"' for n in sorted(names))
    return f"/// {doc}\npub(super) static {name}: &[&str] = &[{items}];\n\n"


out = [
    "// SPDX-License-Identifier: Apache-2.0\n",
    "// Copyright 2026 James Conway\n",
    "\n",
    f"// Generated by scripts/gen-regexp-names.py from the Unicode {VERSION} UCD\n",
    "// and ECMA-262's tables. Don't edit.\n",
    "\n",
    "//! The property names and values `\\p{...}` accepts, sorted.\n",
    "\n",
    table("GENERAL_CATEGORY", "General_Category values and their aliases.", values["gc"]),
    table("SCRIPT", "Script values and their aliases, for Script and Script_Extensions.", values["sc"]),
    table("BINARY", "Binary properties and their aliases.", BINARY),
    table("STRINGS", "Binary properties of strings, which only the v flag has.", STRINGS),
]
with open("src/regexp/names.rs", "w") as f:
    f.write("".join(out).rstrip("\n") + "\n")
subprocess.run(["rustfmt", "--edition", "2024", "src/regexp/names.rs"], check=True)
print({k: len(v) for k, v in values.items()}, len(BINARY), len(STRINGS))
